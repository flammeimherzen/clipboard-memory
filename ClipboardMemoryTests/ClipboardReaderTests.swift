import AppKit
import Testing
@testable import ClipboardMemory

@MainActor
struct ClipboardReaderTests {
    @Test func plainText() {
        let decision = ClipboardReader.decide(snapshot(types: ["public.utf8-plain-text"], plainText: "hello"), redactSecrets: true)
        #expect(decision == .text("hello"))
    }

    @Test func emptyAndWhitespaceAreSkipped() {
        #expect(ClipboardReader.decide(snapshot(types: ["public.utf8-plain-text"], plainText: ""), redactSecrets: true) == .skip)
        #expect(ClipboardReader.decide(snapshot(types: ["public.utf8-plain-text"], plainText: " \n\t "), redactSecrets: true) == .skip)
    }

    @Test func pngImage() {
        let data = Data([0x89, 0x50, 0x4E, 0x47])
        let decision = ClipboardReader.decide(snapshot(types: ["public.png"], pngData: data), redactSecrets: true)
        #expect(decision == .png(data))
    }

    @Test func excelPrefersTextWhenAnImageIsAlongside() {
        let decision = ClipboardReader.decide(
            snapshot(types: ["public.utf8-plain-text", "public.png"], plainText: "42", pngData: Data([1, 2, 3])),
            redactSecrets: true
        )
        #expect(decision == .text("42"))
    }

    @Test func safariCopyImagePrefersTheImage() {
        let data = Data([9, 8, 7])
        let decision = ClipboardReader.decide(
            snapshot(
                types: ["public.utf8-plain-text", "public.url", "public.png"],
                plainText: "https://example.com/cat.png",
                pngData: data
            ),
            redactSecrets: true
        )
        #expect(decision == .png(data))
    }

    @Test func concealedTextFollowsThePasswordSetting() {
        let concealed = snapshot(
            types: ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"],
            plainText: "secret"
        )
        #expect(ClipboardReader.decide(concealed, redactSecrets: true) == .skip)
        #expect(ClipboardReader.decide(concealed, redactSecrets: false) == .text("secret"))

        let passwordManager = snapshot(
            types: ["com.agilebits.onepassword", "public.utf8-plain-text"],
            plainText: "hunter2"
        )
        #expect(ClipboardReader.decide(passwordManager, redactSecrets: true) == .skip)
        #expect(ClipboardReader.decide(passwordManager, redactSecrets: false) == .text("hunter2"))
    }

    @Test func imageFileCopyIsKept() {
        let data = Data([0x89, 0x50, 0x4E, 0x47])
        let decision = ClipboardReader.decide(
            snapshot(
                types: ["public.file-url", "public.png", "public.utf8-plain-text"],
                plainText: "cat.png",
                pngData: data,
                fileURL: "file:///Users/me/Desktop/cat.png",
                prefersImage: true
            ),
            redactSecrets: true
        )
        #expect(decision == .png(data))
    }

    @Test func webArchiveImageIsExtracted() {
        let png = Data([9, 8, 7])
        let archive: [String: Any] = [
            "WebSubresources": [
                [
                    "WebResourceMIMEType": "image/png",
                    "WebResourceData": png
                ]
            ]
        ]
        let data = try! PropertyListSerialization.data(fromPropertyList: archive, format: .binary, options: 0)
        #expect(ClipboardReader.imageData(inWebArchive: data) == png)
    }

    @Test func finderFileURLIsSkipped() {
        let decision = ClipboardReader.decide(
            snapshot(
                types: ["public.file-url", "public.utf8-plain-text", "public.png"],
                plainText: "Notes.txt",
                pngData: Data([1])
            ),
            redactSecrets: true
        )
        #expect(decision == .skip)
    }

    @Test func rtfWithoutPlainText() {
        let source = NSAttributedString(string: "из rtf")
        let rtf = source.rtf(from: NSRange(location: 0, length: source.length))
        let decision = ClipboardReader.decide(
            snapshot(types: ["public.rtf"], rtfData: rtf),
            redactSecrets: true
        )
        #expect(decision == .text("из rtf"))
    }

    @Test func transientIsSkippedEvenWhenPasswordsAreAllowed() {
        let decision = ClipboardReader.decide(
            snapshot(
                types: ["org.nspasteboard.TransientType", "public.utf8-plain-text"],
                plainText: "temp"
            ),
            redactSecrets: false
        )
        #expect(decision == .skip)

        let generated = ClipboardReader.decide(
            snapshot(
                types: ["org.nspasteboard.AutoGeneratedType", "public.utf8-plain-text"],
                plainText: "generated"
            ),
            redactSecrets: false
        )
        #expect(generated == .skip)
    }

    @Test func writerRestoresTextAndImage() throws {
        let root = FileManager.default.temporaryDirectory
            .appending(path: "ClipboardMemoryWriter-\(UUID().uuidString)", directoryHint: .isDirectory)
        let suite = "ClipboardMemoryWriter.\(UUID().uuidString)"
        let defaults = try #require(UserDefaults(suiteName: suite))
        defer {
            try? FileManager.default.removeItem(at: root)
            UserDefaults.standard.removePersistentDomain(forName: suite)
        }
        let store = HistoryStore(root: root, defaults: defaults)
        store.addText("вернуть", source: nil)
        let png = try #require(Data(base64Encoded: "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg=="))
        store.addImage(data: png, fileExtension: "png", source: nil)

        let textBoard = NSPasteboard.withUniqueName()
        defer { textBoard.releaseGlobally() }
        let textItem = try #require(store.items.first { $0.kind == .text })
        #expect(PasteboardWriter.write(textItem, using: store, pasteboard: textBoard) != nil)
        #expect(textBoard.string(forType: .string) == "вернуть")

        let imageBoard = NSPasteboard.withUniqueName()
        defer { imageBoard.releaseGlobally() }
        let imageItem = try #require(store.items.first { $0.kind == .image })
        #expect(PasteboardWriter.write(imageItem, using: store, pasteboard: imageBoard) != nil)
        #expect(imageBoard.data(forType: .png) == png)
        #expect(imageBoard.data(forType: .tiff) != nil)
    }

    @Test func uniquePasteboardTypesReachDecide() {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }

        pasteboard.clearContents()
        pasteboard.setString("hello unique", forType: .string)
        let textSnapshot = ClipboardReader.snapshot(from: pasteboard)
        #expect(ClipboardReader.decide(textSnapshot, redactSecrets: true) == .text("hello unique"))

        pasteboard.clearContents()
        let url = URL(fileURLWithPath: "/tmp")
        #expect(pasteboard.writeObjects([url as NSURL]))
        let fileSnapshot = ClipboardReader.snapshot(from: pasteboard)
        #expect(fileSnapshot.types.contains("public.file-url"))
        #expect(ClipboardReader.decide(fileSnapshot, redactSecrets: true) == .skip)
    }

    private func snapshot(
        types: [String],
        plainText: String? = nil,
        rtfData: Data? = nil,
        htmlData: Data? = nil,
        pngData: Data? = nil,
        jpegData: Data? = nil,
        otherImageData: Data? = nil,
        fileURL: String? = nil,
        prefersImage: Bool = false
    ) -> ClipboardSnapshot {
        ClipboardSnapshot(
            types: types,
            plainText: plainText,
            rtfData: rtfData,
            htmlData: htmlData,
            pngData: pngData,
            jpegData: jpegData,
            otherImageData: otherImageData,
            fileURL: fileURL,
            prefersImage: prefersImage
        )
    }
}
