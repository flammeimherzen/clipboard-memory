import AppKit
import Foundation
import ImageIO

struct ClipboardSnapshot: Equatable, Sendable {
    var types: [String]
    var plainText: String?
    var rtfData: Data?
    var htmlData: Data?
    var pngData: Data?
    var jpegData: Data?
    var otherImageData: Data?
    var fileURL: String? = nil
    /// Image file copies and pictures embedded in a web archive should win over a filename or alt text.
    var prefersImage: Bool = false
}

enum ReadDecision: Equatable, Sendable {
    case text(String)
    case png(Data)
    case jpeg(Data)
    case transcodeImage(Data)
    case skip
}

@MainActor
enum ClipboardReader {
    static func snapshot(from pasteboard: NSPasteboard) -> ClipboardSnapshot {
        let item = pasteboard.pasteboardItems?.first
        let itemTypes = item?.types.map(\.rawValue) ?? []
        let pasteboardTypes = pasteboard.types?.map(\.rawValue) ?? []
        var seen = Set<String>()
        let types = (pasteboardTypes + itemTypes).filter { seen.insert($0).inserted }

        func data(for type: String) -> Data? {
            let pasteboardType = NSPasteboard.PasteboardType(type)
            let value = item?.data(forType: pasteboardType) ?? pasteboard.data(forType: pasteboardType)
            guard let value, !value.isEmpty else { return nil }
            return value
        }

        func string(for type: String) -> String? {
            let pasteboardType = NSPasteboard.PasteboardType(type)
            let value = item?.string(forType: pasteboardType) ?? pasteboard.string(forType: pasteboardType)
            guard let value, !value.isEmpty else { return nil }
            return value
        }

        var pngData = data(for: NSPasteboard.PasteboardType.png.rawValue)
        var jpegData = data(for: "public.jpeg")
        var otherImageData = data(for: NSPasteboard.PasteboardType.tiff.rawValue)
            ?? data(for: "NeXT TIFF v4.0 pasteboard type")
            ?? data(for: "com.compuserve.gif")
            ?? data(for: "public.gif")
            ?? data(for: "public.heic")
            ?? data(for: "public.heif")
        let fileURL = Self.fileURL(from: pasteboard)
        var prefersImage = false

        if let fileURL, Self.isImageFile(fileURL) {
            prefersImage = true
            if let fileData = Self.imageFileData(at: fileURL) {
                switch fileURL.pathExtension.lowercased() {
                case "jpg", "jpeg":
                    jpegData = fileData
                case "png":
                    pngData = fileData
                default:
                    otherImageData = fileData
                }
            }
        }

        if pngData == nil, jpegData == nil, otherImageData == nil,
           let archive = data(for: "com.apple.webarchive") ?? data(for: "Apple Web Archive pasteboard type"),
           let embedded = Self.imageData(inWebArchive: archive) {
            prefersImage = true
            otherImageData = embedded
        }

        if pngData == nil, jpegData == nil, otherImageData == nil,
           let images = pasteboard.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage],
           let tiff = images.first?.tiffRepresentation, !tiff.isEmpty {
            otherImageData = tiff
        }

        return ClipboardSnapshot(
            types: types,
            plainText: string(for: NSPasteboard.PasteboardType.string.rawValue),
            rtfData: data(for: NSPasteboard.PasteboardType.rtf.rawValue) ?? data(for: "NeXT Rich Text Format v1.0 pasteboard type"),
            htmlData: data(for: NSPasteboard.PasteboardType.html.rawValue),
            pngData: pngData,
            jpegData: jpegData,
            otherImageData: otherImageData,
            fileURL: fileURL?.absoluteString,
            prefersImage: prefersImage
        )
    }

    static func imageData(inWebArchive data: Data) -> Data? {
        guard let plist = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any] else {
            return nil
        }
        var resources = plist["WebSubresources"] as? [[String: Any]] ?? []
        if let main = plist["WebMainResource"] as? [String: Any] {
            resources.insert(main, at: 0)
        }
        for resource in resources {
            let mime = (resource["WebResourceMIMEType"] as? String)?.lowercased() ?? ""
            guard mime.hasPrefix("image/"),
                  let bytes = resource["WebResourceData"] as? Data,
                  !bytes.isEmpty else { continue }
            return bytes
        }
        return nil
    }

    static func decide(_ snapshot: ClipboardSnapshot, redactSecrets: Bool) -> ReadDecision {
        let types = Set(snapshot.types)
        if types.contains(Marker.transient) || types.contains(Marker.autoGenerated) {
            return .skip
        }
        if redactSecrets && shouldRedact(types) {
            return .skip
        }
        if let fileURL = snapshot.fileURL.flatMap(URL.init(string:)), !isImageFile(fileURL) {
            return .skip
        }
        if snapshot.fileURL == nil, types.contains(Marker.fileURL) {
            return .skip
        }

        let text = resolvedText(in: snapshot)
        let image = imageDecision(in: snapshot)
        let hasText = text.map { !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty } ?? false

        if snapshot.prefersImage, let image {
            return image
        }
        if hasText, let text, let image {
            if isSingleHTTPURL(text) { return image }
            return .text(text)
        }
        if let image { return image }
        if hasText, let text { return .text(text) }
        return .skip
    }

    private static func shouldRedact(_ types: Set<String>) -> Bool {
        if types.contains(Marker.concealed) { return true }
        return types.contains { type in
            let name = type.lowercased()
            return name.contains("onepassword") || name.contains("agilebits") || name.contains("bitwarden")
        }
    }

    private static func resolvedText(in snapshot: ClipboardSnapshot) -> String? {
        if let plainText = snapshot.plainText, !plainText.isEmpty {
            return plainText
        }
        if let rtfData = snapshot.rtfData,
           let text = attributedString(from: rtfData, type: .rtf)?.string,
           !text.isEmpty {
            return text
        }
        if let htmlData = snapshot.htmlData,
           let text = attributedString(from: htmlData, type: .html)?.string,
           !text.isEmpty {
            return text
        }
        return nil
    }

    private static func attributedString(from data: Data, type: NSAttributedString.DocumentType) -> NSAttributedString? {
        try? NSAttributedString(
            data: data,
            options: [.documentType: type],
            documentAttributes: nil
        )
    }

    private static func imageDecision(in snapshot: ClipboardSnapshot) -> ReadDecision? {
        if let pngData = snapshot.pngData, !pngData.isEmpty {
            return .png(pngData)
        }
        if let jpegData = snapshot.jpegData, !jpegData.isEmpty {
            return .jpeg(jpegData)
        }
        if let otherImageData = snapshot.otherImageData, !otherImageData.isEmpty {
            return .transcodeImage(otherImageData)
        }
        return nil
    }

    private static func isSingleHTTPURL(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, trimmed.rangeOfCharacter(from: .whitespacesAndNewlines) == nil else { return false }
        guard let url = URL(string: trimmed), let scheme = url.scheme?.lowercased() else { return false }
        return scheme == "http" || scheme == "https"
    }

    private static let imageExtensions: Set<String> = [
        "png", "jpg", "jpeg", "gif", "tif", "tiff", "heic", "heif", "webp", "bmp"
    ]

    private static func fileURL(from pasteboard: NSPasteboard) -> URL? {
        if let raw = pasteboard.string(forType: .fileURL),
           let url = URL(string: raw), url.isFileURL {
            return url
        }
        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL]
        return urls?.first { $0.isFileURL }
    }

    private static func isImageFile(_ url: URL) -> Bool {
        imageExtensions.contains(url.pathExtension.lowercased())
    }

    private static func imageFileData(at url: URL) -> Data? {
        let values = try? url.resourceValues(forKeys: [.fileSizeKey])
        if let size = values?.fileSize, size > HistoryStore.maxImageBytes || size == 0 {
            return nil
        }
        return try? Data(contentsOf: url)
    }

    private enum Marker {
        static let concealed = "org.nspasteboard.ConcealedType"
        static let transient = "org.nspasteboard.TransientType"
        static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
        static let fileURL = "public.file-url"
    }
}

@MainActor
enum ImageTranscoder {
    static func pngData(from data: Data) -> (Data, PixelSize)? {
        if let source = CGImageSourceCreateWithData(data as CFData, nil),
           let image = CGImageSourceCreateImageAtIndex(source, 0, nil) {
            let representation = NSBitmapImageRep(cgImage: image)
            if let png = representation.representation(using: .png, properties: [:]) {
                return (png, PixelSize(width: Double(image.width), height: Double(image.height)))
            }
        }
        guard let representation = NSBitmapImageRep(data: data),
              let png = representation.representation(using: .png, properties: [:]) else { return nil }
        return (
            png,
            PixelSize(width: Double(representation.pixelsWide), height: Double(representation.pixelsHigh))
        )
    }

    static func tiffData(from data: Data) -> Data? {
        NSBitmapImageRep(data: data)?.tiffRepresentation
    }
}
